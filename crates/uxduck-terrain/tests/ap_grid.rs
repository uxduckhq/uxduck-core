fn check_grid(rows: &[GridRow]) {
    for &(lat, lon, spacing, lat_deg, lon_deg, grid_lat, grid_lon, gx, gy, ix, iy, fx, fy) in rows {
        let info = grid_info(lat, lon, spacing);
        let at = format!("({lat}, {lon}) every {spacing} m");
        assert_eq!(
            (info.lat_degrees, info.lon_degrees),
            (lat_deg, lon_deg),
            "{at}"
        );
        assert_eq!((info.grid_idx_x, info.grid_idx_y), (gx, gy), "{at}");
        assert_eq!((info.idx_x, info.idx_y), (ix, iy), "{at}");
        // A centimetre between float and double, and between C's and Rust's cosine.
        assert!(
            (info.grid_lat - grid_lat).abs() <= 2,
            "{at}: {} {grid_lat}",
            info.grid_lat
        );
        assert!(
            (info.grid_lon - grid_lon).abs() <= 2,
            "{at}: {} {grid_lon}",
            info.grid_lon
        );
        // Within the square, to a centimetre.
        let metres = |a: f32, b: f32| ((a - b) * f32::from(spacing)).abs();
        assert!(metres(info.frac_x, fx) < 0.01, "{at}: {} {fx}", info.frac_x);
        assert!(metres(info.frac_y, fy) < 0.01, "{at}: {} {fy}", info.frac_y);
    }
}

fn check_offset(rows: &[(i32, i32, f64, f64, i32, i32)]) {
    for &(lat, lon, north, east, lat2, lon2) in rows {
        let (a, b) = offset(lat, lon, north, east);
        let at = format!("({lat}, {lon}) + ({north}, {east})");
        assert!((a - lat2).abs() <= 1, "{at}: {a} {lat2}");
        assert!((b - lon2).abs() <= 1, "{at}: {b} {lon2}");
    }
}

#[test]
fn grid_info_matches_a_flight_controller() {
    check_grid(FLOAT_GRID_INFO);
}

#[test]
fn grid_info_matches_sitl() {
    check_grid(DOUBLE_GRID_INFO);
}

#[test]
fn offset_matches_a_flight_controller() {
    check_offset(FLOAT_OFFSET);
}

#[test]
fn offset_matches_sitl() {
    check_offset(DOUBLE_OFFSET);
}
